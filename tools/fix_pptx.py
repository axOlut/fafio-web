import re
s=open('/tmp/claude-0/pptx_raw.js').read()
s=s.replace('class PptxWriter {','import { Zip, SB, esc, XML_HEAD } from "./util.js";\nimport { lines as docLines } from "./doc.js";\n\n/** Génère une présentation PowerPoint (.pptx). assets = { "pptx/theme1.xml": "...", ... }. Renvoie un Uint8Array. */\nexport function writePptx(doc, assets) {',1)
